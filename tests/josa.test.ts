import { describe, expect, it } from "vitest";
import { josa } from "../src/ui/josa";

describe("조사 자동 교정", () => {
  it.each([
    ["신라이(가) 이겼다", "신라가 이겼다"],
    ["김유신이(가) 출전", "김유신이 출전"],
    ["계백을(를) 등용", "계백을 등용"],
    ["고구려을(를) 공격", "고구려를 공격"],
    ["연개소문은(는)", "연개소문은"],
    ["당과(와) 동맹", "당과 동맹"],
    ["고구려과(와) 동맹", "고구려와 동맹"],
    ["평양(으)로", "평양으로"],
    ["웅진성(으)로", "웅진성으로"],
    ["사비(으)로", "사비로"],
    ["국내성(으)로", "국내성으로"],
    ["3(으)로", "3으로"],
    ["7(으)로", "7로"],
    ["10이(가)", "10이"],
    ["ABC이(가)", "ABC이(가)"],
  ])("%s → %s", (src, want) => {
    expect(josa(src)).toBe(want);
  });
});
